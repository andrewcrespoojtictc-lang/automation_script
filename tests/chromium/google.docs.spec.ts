import { test, chromium, expect } from '@playwright/test';

test('create a Google Doc, add content, and rename it', async () => {
  const browser = await chromium.connectOverCDP('http://localhost:9222');
  const context = browser.contexts()[0];
  const page = context.pages()[0] ?? (await context.newPage());

  // 1. Create a blank document
  await page.goto('https://docs.google.com/document/u/0');
  await page.getByRole('option', { name: 'Blank document' }).click();

  // 2. Wait for the editor, then focus it
  const editor = page.locator('.kix-page-paginated');
  await editor.waitFor({ state: 'visible', timeout: 30000 });
  await editor.click();

  // 3. Type content (keyboard goes to Docs' hidden input iframe automatically)
  await page.keyboard.press('ControlOrMeta+Alt+1');   // Heading 1
  await page.keyboard.type('Automated Report');
  await page.keyboard.press('Enter');
  await page.keyboard.press('ControlOrMeta+Alt+0');   // back to normal text

  await page.keyboard.press('ControlOrMeta+b');       // bold on
  await page.keyboard.type('Generated by Playwright. ');
  await page.keyboard.press('ControlOrMeta+b');       // bold off
  await page.keyboard.type('This line is normal text.');

  // 4. Rename the document
  const rename = page.getByRole('textbox', { name: 'Rename' });
  await rename.click();
  await rename.fill('Automated by Playwright');
  await rename.press('Enter');

  // 5. Check the title was saved
  await expect(rename).toHaveValue('Automated by Playwright');

  // 6. Back to Docs home
  await page.getByRole('link', { name: 'Docs home' }).click();
});