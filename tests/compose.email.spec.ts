// LOOP 3 TIMES

test('compose and send email 5 times', async () => {
  // test.setTimeout(120000);

  const browser = await chromium.connectOverCDP('http://localhost:9222');
  const context = browser.contexts()[0];

  // Prefer an existing Gmail tab; otherwise open a fresh one
  let page: Page | undefined = context
    .pages()
    .find((p) => p.url().startsWith('https://mail.google.com'));

  if (!page) {
    page = await context.newPage();
    await page.goto('https://mail.google.com/mail/u/0/', {
      waitUntil: 'domcontentloaded',
    });
  }

  // Wait for the inbox UI instead of relying on the "load" event
  await page.getByRole('button', { name: 'Compose' }).waitFor({ timeout: 30000 });

  for (let i = 1; i <= 5; i++) {
    await page.getByRole('button', { name: 'Compose' }).click();
    await page.getByRole('combobox', { name: 'To recipients' }).fill('batcrespo063@gmail.com');
    await page.getByRole('textbox', { name: 'Subject' }).fill(`From Playwright Script #${i}`);
    await page.getByRole('textbox', { name: 'Message Body' }).fill(`Generated by Playwright Script (email ${i} of 5)`);
    await page.getByRole('button', { name: /^Send/ }).click();

    await page.getByRole('textbox', { name: 'Message Body' }).waitFor({ state: 'detached' });
  }
});

